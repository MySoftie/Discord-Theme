# Discord-Theme
This is where I code Discord Themes for fun

## How to Use & Customize
All themes I use will have a root, where you can easily change the color

1. Open Vencord QuickEditer CSS,
2. Locate the root variables section
3. Change the hex color codes (`#000000` or `#ffffff`) to the colors you want

```css
:root {
    /* Modify these to change the theme colors */
    --primary-color: #000000;
    --accent-color: #ffffff;
}
```

## How to add just the add-on
If you want some of my add-on here the steps

1. **Find the File:** Click on the Add-on file you want in this repository
2. **Copy the Link:** Look at the top header near my credits and copy the link that looks like this:
   ```css
   @import url("#");
   ```
3. **Paste the Code:** Paste that line at the top of of you Css


